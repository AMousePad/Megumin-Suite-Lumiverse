// ─────────────────────────────────────────────────────────────────────────────
// Build: style.css -> an inlined stylesheet, then both bundles.
//
//   bun run build.mjs
//
// The source tree under src/ is the SillyTavern build of the suite, kept as
// close to it as possible. Two things make that work on Lumiverse:
//
//   - src/st.js is the host shim. Every SillyTavern import in the suite already
//     goes through that one file, so replacing it moves the suite to Lumiverse.
//
//   - The globals SillyTavern put on window ($, jQuery, toastr) are supplied by
//     the plugin below as an import added to each file that uses them. See
//     src/lumi/globals.js.
//
// Lumiverse has no way to serve an extension's own files to the browser, so the
// stylesheet is embedded in the frontend bundle as a string.
// ─────────────────────────────────────────────────────────────────────────────

import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve, sep } from "node:path";

const root = import.meta.dir;
const src = join(root, "src");
const globalsPath = join(src, "lumi", "globals.js");

// ── Stylesheet ───────────────────────────────────────────────────────────────
const css = readFileSync(join(root, "style.css"), "utf8")
    + "\n\n/* ── Lumiverse ── */\n"
    + readFileSync(join(src, "lumi", "lumi.css"), "utf8");
writeFileSync(
    join(src, "lumi", "styles.generated.js"),
    "// GENERATED by build.mjs from style.css and src/lumi/lumi.css. Do not edit.\n"
    + `export const MEGUMIN_STYLES = ${JSON.stringify(css)};\n`,
);

// ── The globals plugin ───────────────────────────────────────────────────────
const USES_GLOBALS = /(^|[^\w$.])(\$|jQuery|toastr)\s*(\(|\.)/m;

const globalsPlugin = {
    name: "megumin-globals",
    setup(build) {
        build.onLoad({ filter: /\.js$/ }, (args) => {
            const path = resolve(args.path);
            const contents = readFileSync(path, "utf8");
            const inSrc = path.startsWith(src + sep);
            if (!inSrc || path === globalsPath || path.endsWith(`${sep}lumi${sep}bridge.js`)) {
                return { contents, loader: "js" };
            }
            if (!USES_GLOBALS.test(contents) || contents.includes("lumi/globals.js")) return { contents, loader: "js" };
            const spec = JSON.stringify(globalsPath.split(sep).join("/"));
            return { contents: `import { $, jQuery, toastr } from ${spec};\n${contents}`, loader: "js" };
        });
    },
};

async function bundle(entry, outfile, target, plugins = []) {
    const result = await Bun.build({
        entrypoints: [join(src, entry)],
        outdir: join(root, "dist"),
        naming: outfile,
        target,
        format: "esm",
        plugins,
    });
    if (!result.success) {
        for (const log of result.logs) console.error(log);
        throw new Error(`build of ${entry} failed`);
    }
    console.log(`built dist/${outfile}`);
}

await bundle("frontend.js", "frontend.js", "browser", [globalsPlugin]);
await bundle("backend.js", "backend.js", "bun");
